export const INK = '#1e1b17';
export const P = (d, f, w = 0, s = INK) =>
  `<path d="${d}" fill="${f || 'none'}"${w ? ` stroke="${s}" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"` : ''}/>`;
export const L = (d, w, c) => `<path d="${d}" fill="none" stroke="${c}" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"/>`;
export const C = (x, y, r, f, w = 0, s = INK) =>
  `<circle cx="${x}" cy="${y}" r="${r}" fill="${f || 'none'}"${w ? ` stroke="${s}" stroke-width="${w}"` : ''}/>`;
export const star5 = (cx, cy, r, f, w = 1.4) => {
  let d = '';
  for (let i = 0; i < 10; i++) { const a = -Math.PI / 2 + i * Math.PI / 5, rr = i % 2 ? r * .42 : r;
    d += (i ? 'L' : 'M') + (cx + Math.cos(a) * rr).toFixed(1) + ' ' + (cy + Math.sin(a) * rr).toFixed(1); }
  return P(d + 'Z', f, w);
};
