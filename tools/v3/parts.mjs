  const x = 50 - W / 2;
  if (kind === 'bob')  return { b: P(`M${x - 4} 30 q0 -26 ${W / 2 + 4} -26 q${W / 2 + 4} 0 ${W / 2 + 4} 26 l0 22 q-6 4 -9 -2 l-2 -20 q-8 -8 -${W / 2 + 4} -8 q-${W / 2 - 4} 0 -${W / 2 + 4} 8 l-2 20 q-3 6 -9 2 Z`, col, 2.6), f: '' };
